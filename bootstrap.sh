#!/usr/bin/env bash
set -Eeuo pipefail

namespace=openbao
credentials=.openbao
init_file="$credentials/init.json"

# Keep the initialization data outside the cluster with restricted permissions.
mkdir -p "$credentials"
chmod 700 "$credentials"

# Wait until all OpenBao containers are running before using the CLI.
wait_for_pods() {
  for pod in openbao-0 openbao-1 openbao-2; do
    kubectl wait --for=jsonpath='{.status.phase}'=Running \
      -n "$namespace" "pod/$pod" --timeout=5m >/dev/null
  done
}

# Treat status code 2 (sealed) as a valid OpenBao state during bootstrap.
status() {
  local pod=$1 output code

  if output="$(kubectl exec -n "$namespace" "$pod" -- bao status 2>&1)"; then
    printf '%s\n' "$output"
    return 0
  else
    code=$?
  fi

  [ "$code" -eq 2 ] || {
    printf '%s\n' "$output" >&2
    return "$code"
  }
  printf '%s\n' "$output"
  return 0
}

# Apply three Shamir key shares to unseal one OpenBao pod.
unseal() {
  local pod=$1
  kubectl exec -n "$namespace" "$pod" -- bao operator unseal "$key1" >/dev/null
  kubectl exec -n "$namespace" "$pod" -- bao operator unseal "$key2" >/dev/null
  kubectl exec -n "$namespace" "$pod" -- bao operator unseal "$key3" >/dev/null
}

# Initialize OpenBao only when the shared PostgreSQL storage is not initialized.
wait_for_pods

if ! status="$(status openbao-0)"; then
  echo "$status" >&2
  exit 1
fi

if ! grep -q 'Initialized.*true' <<<"$status"; then
  [ ! -e "$init_file" ] || {
    echo "refusing to overwrite $init_file" >&2
    exit 1
  }
  echo "Creating OpenBao Shamir keys"
  umask 077
  kubectl exec -n "$namespace" openbao-0 -- bao operator init -format=json > "$init_file"
  chmod 600 "$init_file"
fi

# Read the keys and root token generated by the initialization step.
[ -s "$init_file" ] || {
  echo "missing OpenBao credentials: $init_file" >&2
  exit 1
}

key1="$(jq -r '.unseal_keys_b64[0]' "$init_file")"
key2="$(jq -r '.unseal_keys_b64[1]' "$init_file")"
key3="$(jq -r '.unseal_keys_b64[2]' "$init_file")"
jq -r '.root_token' "$init_file" > "$credentials/root-token"
chmod 600 "$credentials/root-token"

# Unseal every replica and wait until Kubernetes reports it Ready.
for pod in openbao-0 openbao-1 openbao-2; do
  if grep -q 'Sealed.*true' <<<"$(status "$pod")"; then
    unseal "$pod"
  fi
  kubectl wait --for=condition=Ready -n "$namespace" "pod/$pod" --timeout=5m >/dev/null
done
